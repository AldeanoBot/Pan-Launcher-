export function buildWindowsSelfContainedBat(
  appZipBase64: string,
  buildVersion: string
): string {
  const runPs1 = buildWindowsRunPs1(buildVersion);
  const runPs1B64 = Buffer.from(runPs1, 'utf8').toString('base64');

  const psCommand = [
    '$self = [IO.File]::ReadAllText($env:PAN_SELF)',
    "$k1 = '::PAN_PS_' + 'B64::'",
    "$k2 = '::PAN_ZIP_' + 'B64::'",
    '$i1 = $self.LastIndexOf($k1)',
    '$i2 = $self.LastIndexOf($k2)',
    '$psB64 = $self.Substring($i1 + $k1.Length, $i2 - ($i1 + $k1.Length)).Trim()',
    '$zipB64 = $self.Substring($i2 + $k2.Length).Trim()',
    "$dir = Join-Path $env:LOCALAPPDATA 'Pan-launcher'",
    'New-Item -ItemType Directory -Force -Path $dir | Out-Null',
    "[IO.File]::WriteAllText((Join-Path $dir 'run.ps1'), [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($psB64)), [Text.Encoding]::UTF8)",
    "[IO.File]::WriteAllBytes((Join-Path $dir 'app.zip'), [Convert]::FromBase64String($zipB64))",
    "Copy-Item -LiteralPath $env:PAN_SELF -Destination (Join-Path $dir 'Pan-launcher.bat') -Force",
    "& (Join-Path $dir 'run.ps1')",
  ].join('; ');

  return [
    '@echo off',
    'chcp 65001 >nul',
    'title Pan-launcher - Instalando App Nativa (.exe)...',
    'echo Preparando Pan-launcher.exe en tu PC (sin Chrome)...',
    'set "PAN_SELF=%~f0"',
    `powershell -NoProfile -ExecutionPolicy Bypass -Command "${psCommand}"`,
    'exit /b',
    '::PAN_PS_B64::',
    runPs1B64,
    '::PAN_ZIP_B64::',
    appZipBase64,
    '',
  ].join('\r\n');
}

export function buildUnixSelfContainedSh(
  appZipBase64: string,
  buildVersion: string
): string {
  const safeVersion = buildVersion.replace(/[^a-zA-Z0-9._-]/g, '') || '1.0.0';
  return [
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    'APP_BASE="$HOME/.local/share/pan-launcher"',
    'APP_DIR="$APP_BASE/app"',
    'VER_FILE="$APP_BASE/version.txt"',
    'PORT=41735',
    'URL="http://127.0.0.1:$PORT/"',
    'mkdir -p "$APP_BASE"',
    '',
    `TARGET_VER="${safeVersion}"`,
    'CUR_VER=""',
    '[ -f "$VER_FILE" ] && CUR_VER="$(cat "$VER_FILE")"',
    'if [ ! -f "$APP_DIR/index.html" ] || [ "$CUR_VER" != "$TARGET_VER" ]; then',
    '  rm -rf "$APP_DIR" && mkdir -p "$APP_DIR"',
    '  ARCHIVE_LINE=$(awk \'/^__PAN_ZIP_B64__$/{print NR + 1; exit 0;}\' "$0")',
    '  tail -n+"$ARCHIVE_LINE" "$0" | base64 --decode > "$APP_BASE/app.zip" 2>/dev/null || tail -n+"$ARCHIVE_LINE" "$0" | base64 -D > "$APP_BASE/app.zip"',
    '  python3 -m zipfile -e "$APP_BASE/app.zip" "$APP_DIR"',
    '  printf "%s" "$TARGET_VER" > "$VER_FILE"',
    'fi',
    '',
    'if ! curl -fsS "http://127.0.0.1:$PORT/" >/dev/null 2>&1; then',
    '  nohup python3 -m http.server "$PORT" --bind 127.0.0.1 --directory "$APP_DIR" >/dev/null 2>&1 &',
    '  sleep 0.6',
    'fi',
    '',
    'if [[ "$OSTYPE" == "darwin"* ]]; then',
    '  if [ -d "/Applications/Google Chrome.app" ]; then',
    '    open -a "Google Chrome" --args --app="$URL"',
    '  elif [ -d "/Applications/Microsoft Edge.app" ]; then',
    '    open -a "Microsoft Edge" --args --app="$URL"',
    '  else',
    '    open "$URL"',
    '  fi',
    'elif command -v google-chrome >/dev/null 2>&1; then',
    '  google-chrome --app="$URL" >/dev/null 2>&1 &',
    'elif command -v chromium >/dev/null 2>&1; then',
    '  chromium --app="$URL" >/dev/null 2>&1 &',
    'else',
    '  xdg-open "$URL"',
    'fi',
    'exit 0',
    '__PAN_ZIP_B64__',
    appZipBase64,
    '',
  ].join('\n');
}
