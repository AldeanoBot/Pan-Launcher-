function alignUp(value: number, alignment: number): number {
  if (alignment <= 0) return value;
  return Math.ceil(value / alignment) * alignment;
}

export function computePeCheckSum(peBuffer: Buffer, checksumOffset: number): number {
  let sum = 0;
  const len = peBuffer.length;
  for (let i = 0; i + 1 < len; i += 2) {
    if (i === checksumOffset || i === checksumOffset + 2) continue;
    sum += peBuffer.readUInt16LE(i);
    sum = (sum & 0xffff) + (sum >>> 16);
  }
  if ((len & 1) !== 0) {
    sum += peBuffer[len - 1];
    sum = (sum & 0xffff) + (sum >>> 16);
  }
  sum = (sum & 0xffff) + (sum >>> 16);
  return (sum + len) >>> 0;
}

export function buildWindowsExe(
  stubBuffer: Buffer,
  bundleZipBuffer: Buffer,
  _buildVersion: string
): Buffer {
  if (stubBuffer.length < 0x100 || stubBuffer.readUInt16LE(0) !== 0x5a4d) {
    throw new Error('La plantilla nativa pan-stub.exe no tiene cabecera PE válida.');
  }

  const peOffset = stubBuffer.readUInt32LE(0x3c);
  if (
    peOffset <= 0 ||
    peOffset + 264 > stubBuffer.length ||
    stubBuffer.toString('ascii', peOffset, peOffset + 4) !== 'PE\0\0'
  ) {
    throw new Error('Cabecera NT inválida en pan-stub.exe.');
  }

  const numSections = stubBuffer.readUInt16LE(peOffset + 6);
  const optHeaderSize = stubBuffer.readUInt16LE(peOffset + 20);
  const optStart = peOffset + 24;
  const secTableStart = optStart + optHeaderSize;
  const newSecHeaderOff = secTableStart + numSections * 40;
  const sectionAlignment = stubBuffer.readUInt32LE(optStart + 32);
  const fileAlignment = stubBuffer.readUInt32LE(optStart + 36);
  const sizeOfHeaders = stubBuffer.readUInt32LE(optStart + 60);
  const checksumOffset = optStart + 64;

  if (newSecHeaderOff + 40 > sizeOfHeaders) {
    throw new Error('No hay espacio libre en SizeOfHeaders para añadir la sección .panpkg.');
  }

  const lastSecOff = secTableStart + (numSections - 1) * 40;
  const lastVSize = stubBuffer.readUInt32LE(lastSecOff + 8);
  const lastVA = stubBuffer.readUInt32LE(lastSecOff + 12);
  const lastRawSize = stubBuffer.readUInt32LE(lastSecOff + 16);

  const newVA = alignUp(lastVA + Math.max(lastVSize, lastRawSize), sectionAlignment);
  const newRawPtr = alignUp(stubBuffer.length, fileAlignment);
  const newRawSize = alignUp(bundleZipBuffer.length, fileAlignment);
  const newSizeOfImage = alignUp(newVA + bundleZipBuffer.length, sectionAlignment);

  const outBuf = Buffer.alloc(newRawPtr + newRawSize, 0);
  stubBuffer.copy(outBuf, 0);
  bundleZipBuffer.copy(outBuf, newRawPtr);

  // Write .panpkg section header
  outBuf.write('.panpkg\0', newSecHeaderOff, 8, 'ascii');
  outBuf.writeUInt32LE(bundleZipBuffer.length, newSecHeaderOff + 8); // VirtualSize
  outBuf.writeUInt32LE(newVA, newSecHeaderOff + 12); // VirtualAddress
  outBuf.writeUInt32LE(newRawSize, newSecHeaderOff + 16); // SizeOfRawData
  outBuf.writeUInt32LE(newRawPtr, newSecHeaderOff + 20); // PointerToRawData
  outBuf.writeUInt32LE(0x40000040, newSecHeaderOff + 36); // CNT_INITIALIZED_DATA | MEM_READ

  // Update NT headers
  outBuf.writeUInt16LE(numSections + 1, peOffset + 6);
  outBuf.writeUInt32LE(newSizeOfImage, optStart + 56);
  outBuf.writeUInt32LE(0, checksumOffset);

  const checksum = computePeCheckSum(outBuf, checksumOffset);
  outBuf.writeUInt32LE(checksum, checksumOffset);

  return outBuf;
}

