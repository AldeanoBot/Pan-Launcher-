  const DICTS = Object.freeze({ es: ES, en: EN });

  function safeStorageGet(key) {
    try {
      return window.localStorage ? window.localStorage.getItem(key) : null;
    } catch {
      return null;
    }
  }

  function safeStorageSet(key, value) {
    try {
      if (window.localStorage) window.localStorage.setItem(key, value);
    } catch {
      // Ignore quota/private mode errors
    }
  }

  function normalizeLang(raw) {
    const s = String(raw || '').trim().toLowerCase();
    return s === 'en' || s.startsWith('en-') || s.startsWith('en_') ? 'en' : 'es';
  }

  function queryLangOverride() {
    try {
      const search = String((window.location && window.location.search) || '');
      const m = search.match(/[?&]lang=(es|en)(?:&|$)/i);
      return m ? m[1].toLowerCase() : null;
    } catch {
      return null;
    }
  }

  function getLang() {
    const override = queryLangOverride();
    if (override) return normalizeLang(override);
    const saved = safeStorageGet(STORAGE_KEY);
    if (saved === 'es' || saved === 'en') return saved;
    const cfgLang = Nexus.state && Nexus.state.config && Nexus.state.config.general && Nexus.state.config.general.language;
    return cfgLang === 'en' ? 'en' : 'es';
  }

  function hasChosenLang() {
    if (queryLangOverride()) return true;
    const saved = safeStorageGet(STORAGE_KEY);
    return saved === 'es' || saved === 'en';
  }

  function t(key, vars) {
    const lang = getLang();
    const dict = DICTS[lang] || ES;
    const template = Object.prototype.hasOwnProperty.call(dict, key)
      ? dict[key]
      : (Object.prototype.hasOwnProperty.call(ES, key) ? ES[key] : key);
    if (!vars) return template;
    return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (full, k) => {
      if (!Object.prototype.hasOwnProperty.call(vars, k)) return full;
      const val = vars[k];
      return val === undefined || val === null ? '' : String(val);
    });
  }

  function escapeHtml(value) {
    return String(value === undefined || value === null ? '' : value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }

  function hydrateShell() {
    if (typeof document === 'undefined') return;
    const lang = getLang();
    if (document.documentElement) {
      document.documentElement.lang = lang;
    }
    const nav = document.querySelector('.nav');
    if (nav) nav.setAttribute('aria-label', t('shell.navAria'));

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(key));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', t(key));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });

    const langBtnText = document.getElementById('lang-switch-text');
    if (langBtnText) {
      langBtnText.textContent = t('shell.langBtnLabel');
    }
    const langBtn = document.getElementById('btn-lang-switch');
    if (langBtn) {
      langBtn.setAttribute('title', t('shell.langSwitchTitle'));
      langBtn.setAttribute('aria-label', t('shell.langSwitchTitle'));
    }
  }

  function setLang(rawLang, options) {
    const lang = normalizeLang(rawLang);
    safeStorageSet(STORAGE_KEY, lang);
    hydrateShell();
    if (options && options.syncConfig !== false && Nexus.api && typeof Nexus.api.updateConfig === 'function' && Nexus.state && Nexus.state.config) {
      Nexus.state.config.general.language = lang;
      Nexus.api.updateConfig({ general: { language: lang } })
        .then((cfg) => {
          if (Nexus.state) Nexus.state.config = cfg;
        })
        .catch(() => {});
    }
    if (Nexus.router && typeof Nexus.router.refresh === 'function') {
      Nexus.router.refresh();
    }
    if (Nexus.tour && typeof Nexus.tour.isActive === 'function' && Nexus.tour.isActive()) {
      const idx = typeof Nexus.tour.getActiveIndex === 'function' ? Nexus.tour.getActiveIndex() : 0;
      Nexus.tour.start(idx);
    }
    return lang;
  }

  function showLanguageModal(onSelected) {
    if (typeof document === 'undefined' || !document.body) return;
    const existing = document.getElementById('pan-lang-modal');
    if (existing) existing.remove();

    const overlay = document.createElement('div');
    overlay.id = 'pan-lang-modal';
    overlay.className = 'pan-modal-backdrop pan-lang-backdrop';
    overlay.setAttribute('role', 'dialog');
    overlay.setAttribute('aria-modal', 'true');
    overlay.setAttribute('aria-labelledby', 'pan-lang-title');

    overlay.innerHTML = `
      <div class="pan-modal pan-lang-modal">
        <div class="pan-lang-head">
          <span class="badge badge-release">${escapeHtml(t('langModal.badge'))}</span>
          <h2 id="pan-lang-title">${escapeHtml(ES['langModal.title'])}</h2>
          <p class="pan-modal-subtitle">
            Elige el idioma de Pan Launcher / Select Pan Launcher’s language. Podrás cambiarlo después arriba o en Ajustes.
          </p>
        </div>
        <div class="pan-lang-grid">
          <button type="button" class="pan-lang-card" data-choose-lang="es">
            <span class="pan-lang-code">ES</span>
            <div>
              <strong>Español</strong>
              <small>${escapeHtml(ES['langModal.esDesc'])}</small>
            </div>
          </button>
          <button type="button" class="pan-lang-card" data-choose-lang="en">
            <span class="pan-lang-code">EN</span>
            <div>
              <strong>English</strong>
              <small>${escapeHtml(EN['langModal.enDesc'])}</small>
            </div>
          </button>
        </div>
      </div>`;

    overlay.addEventListener('click', (ev) => {
      const btn = ev.target.closest('[data-choose-lang]');
      if (!btn) return;
      const chosen = normalizeLang(btn.getAttribute('data-choose-lang'));
      overlay.remove();
      setLang(chosen, { syncConfig: true });
      if (typeof onSelected === 'function') {
        onSelected(chosen);
      }
    });

    document.body.appendChild(overlay);
  }

  Nexus.i18n = Object.freeze({
    STORAGE_KEY,
    DICTS,
    getLang,
    hasChosenLang,
    normalizeLang,
    setLang,
    t,
    hydrateShell,
    showLanguageModal
  });
